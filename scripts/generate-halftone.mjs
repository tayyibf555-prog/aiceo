/*
  Logo pipeline. Reads public/brand/logo-lockup.png (2048² canvas, lockup
  floating in the middle: blue arrow-A + blue I bar, black "ceo") and emits:

    1. src/lib/halftone-data.ts     — 0/1 grid of the arrow mark for <LogoHalftone>
    2. public/brand/mark-crop.png   — clean accent-blue arrow silhouette on
                                      transparent bg (favicon / OG source)
    3. public/brand/logo-lockup-trim.png — the lockup cropped to content (nav)

  Content detection is COLOUR based (blue-dominant or dark pixels), never
  alpha based, because the source PNG's transparency is unconfirmed.
  Deterministic: same input file → byte-identical outputs.

  Run: node scripts/generate-halftone.mjs
*/
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const SRC = "public/brand/logo-lockup.png";
const GRID_COLS = 40; // halftone resolution across the mark
const COVERAGE_ON = 0.3; // fraction of blue pixels in a cell to switch it on
const ACCENT = { r: 0x1d, g: 0x6b, b: 0xff };

const img = sharp(SRC);
const meta = await img.metadata();
const W = 1024; // working resolution
const scale = W / meta.width;
const H = Math.round(meta.height * scale);
const raw = await img
  .resize(W, H, { fit: "fill" })
  .ensureAlpha()
  .raw()
  .toBuffer();

const idx = (x, y) => (y * W + x) * 4;
const isBlue = (x, y) => {
  const i = idx(x, y);
  const [r, g, b, a] = [raw[i], raw[i + 1], raw[i + 2], raw[i + 3]];
  return a > 128 && b > r + 40 && b > g + 40;
};
const isDark = (x, y) => {
  const i = idx(x, y);
  const [r, g, b, a] = [raw[i], raw[i + 1], raw[i + 2], raw[i + 3]];
  return a > 128 && 0.299 * r + 0.587 * g + 0.114 * b < 160;
};

// Alpha stats, to settle the transparency question in the report
let aMin = 255;
for (let i = 3; i < raw.length; i += 4) if (raw[i] < aMin) aMin = raw[i];

// ── bounding boxes ──────────────────────────────────────────────────────
function bbox(test) {
  let x0 = W, y0 = H, x1 = -1, y1 = -1;
  for (let y = 0; y < H; y++)
    for (let x = 0; x < W; x++)
      if (test(x, y)) {
        if (x < x0) x0 = x;
        if (x > x1) x1 = x;
        if (y < y0) y0 = y;
        if (y > y1) y1 = y;
      }
  if (x1 < 0) throw new Error("no matching pixels");
  return { x0, y0, x1, y1 };
}

const blueBox = bbox(isBlue);
const contentBox = bbox((x, y) => isBlue(x, y) || isDark(x, y));

// Split the blue region into glyphs by empty-column gaps; the arrow-A is
// the widest component (the I bar is narrow).
const colCounts = new Array(blueBox.x1 - blueBox.x0 + 1).fill(0);
for (let x = blueBox.x0; x <= blueBox.x1; x++)
  for (let y = blueBox.y0; y <= blueBox.y1; y++)
    if (isBlue(x, y)) colCounts[x - blueBox.x0]++;

const components = [];
let start = null;
for (let c = 0; c <= colCounts.length; c++) {
  const filled = c < colCounts.length && colCounts[c] > 0;
  if (filled && start === null) start = c;
  if (!filled && start !== null) {
    components.push({ x0: blueBox.x0 + start, x1: blueBox.x0 + c - 1 });
    start = null;
  }
}
const arrowCols = components.reduce((a, b) =>
  b.x1 - b.x0 > a.x1 - a.x0 ? b : a
);
const arrowBox = bbox(
  (x, y) => x >= arrowCols.x0 && x <= arrowCols.x1 && isBlue(x, y)
);

// ── 1. halftone grid of the arrow ───────────────────────────────────────
const pad = Math.round((arrowBox.x1 - arrowBox.x0) * 0.04);
const ax0 = Math.max(0, arrowBox.x0 - pad);
const ay0 = Math.max(0, arrowBox.y0 - pad);
const ax1 = Math.min(W - 1, arrowBox.x1 + pad);
const ay1 = Math.min(H - 1, arrowBox.y1 + pad);
const aw = ax1 - ax0 + 1;
const ah = ay1 - ay0 + 1;
const rows = Math.max(1, Math.round((GRID_COLS * ah) / aw));
const cells = new Array(GRID_COLS * rows).fill(0);

for (let gy = 0; gy < rows; gy++) {
  for (let gx = 0; gx < GRID_COLS; gx++) {
    const px0 = ax0 + Math.floor((gx * aw) / GRID_COLS);
    const px1 = ax0 + Math.floor(((gx + 1) * aw) / GRID_COLS);
    const py0 = ay0 + Math.floor((gy * ah) / rows);
    const py1 = ay0 + Math.floor(((gy + 1) * ah) / rows);
    let on = 0;
    let total = 0;
    for (let y = py0; y < py1; y++)
      for (let x = px0; x < px1; x++) {
        total++;
        if (isBlue(x, y)) on++;
      }
    if (total > 0 && on / total >= COVERAGE_ON)
      cells[gy * GRID_COLS + gx] = 1;
  }
}

const ts = `/* GENERATED by scripts/generate-halftone.mjs — do not edit. */
export const MARK_GRID = {
  cols: ${GRID_COLS},
  rows: ${rows},
  cells: [
${(() => {
  const lines = [];
  for (let r = 0; r < rows; r++)
    lines.push(
      "    " + cells.slice(r * GRID_COLS, (r + 1) * GRID_COLS).join(", ") + ","
    );
  return lines.join("\n");
})()}
  ],
} as const;
`;
writeFileSync("src/lib/halftone-data.ts", ts);

// ── 2. mark silhouette (accent on transparent), 512px ───────────────────
const mw = ax1 - ax0 + 1;
const mh = ay1 - ay0 + 1;
const mark = Buffer.alloc(mw * mh * 4);
for (let y = 0; y < mh; y++)
  for (let x = 0; x < mw; x++) {
    const o = (y * mw + x) * 4;
    if (isBlue(ax0 + x, ay0 + y)) {
      mark[o] = ACCENT.r;
      mark[o + 1] = ACCENT.g;
      mark[o + 2] = ACCENT.b;
      mark[o + 3] = 255;
    }
  }
const markSize = 512;
const fitted = mw >= mh ? { width: markSize } : { height: markSize };
await sharp(mark, { raw: { width: mw, height: mh, channels: 4 } })
  .resize({ ...fitted, fit: "inside" })
  .png()
  .toFile("public/brand/mark-crop.png");

// ── 3. trimmed lockup for the nav ───────────────────────────────────────
const tpadX = Math.round((contentBox.x1 - contentBox.x0) * 0.03);
const tpadY = Math.round((contentBox.y1 - contentBox.y0) * 0.12);
const fullScale = meta.width / W; // map working coords back to source res
const region = {
  left: Math.max(0, Math.round((contentBox.x0 - tpadX) * fullScale)),
  top: Math.max(0, Math.round((contentBox.y0 - tpadY) * fullScale)),
};
region.width = Math.min(
  meta.width - region.left,
  Math.round((contentBox.x1 - contentBox.x0 + 1 + 2 * tpadX) * fullScale)
);
region.height = Math.min(
  meta.height - region.top,
  Math.round((contentBox.y1 - contentBox.y0 + 1 + 2 * tpadY) * fullScale)
);
await sharp(SRC).extract(region).png().toFile("public/brand/logo-lockup-trim.png");

// ── 4. clean lockup (blue→accent, dark→ink, else transparent) ───────────
// The source is opaque with a faint checkered texture; reconstructing from
// the colour masks gives a crisp transparent-bg version for the nav.
const cw = contentBox.x1 - contentBox.x0 + 1 + 2 * tpadX;
const ch = contentBox.y1 - contentBox.y0 + 1 + 2 * tpadY;
const clean = Buffer.alloc(cw * ch * 4);
const INK = { r: 0x0a, g: 0x0a, b: 0x0a };
for (let y = 0; y < ch; y++)
  for (let x = 0; x < cw; x++) {
    const sx = contentBox.x0 - tpadX + x;
    const sy = contentBox.y0 - tpadY + y;
    if (sx < 0 || sy < 0 || sx >= W || sy >= H) continue;
    const o = (y * cw + x) * 4;
    if (isBlue(sx, sy)) {
      clean[o] = ACCENT.r;
      clean[o + 1] = ACCENT.g;
      clean[o + 2] = ACCENT.b;
      clean[o + 3] = 255;
    } else if (isDark(sx, sy)) {
      clean[o] = INK.r;
      clean[o + 1] = INK.g;
      clean[o + 2] = INK.b;
      clean[o + 3] = 255;
    }
  }
await sharp(clean, { raw: { width: cw, height: ch, channels: 4 } })
  .png()
  .toFile("public/brand/logo-lockup-clean.png");

// ── report ──────────────────────────────────────────────────────────────
console.log(`source: ${meta.width}x${meta.height}, alphaMin=${aMin} (${aMin === 255 ? "fully opaque" : "has transparency"})`);
console.log(`blue components: ${components.length} → arrow = widest`);
console.log(`halftone grid: ${GRID_COLS}x${rows}, on cells: ${cells.filter(Boolean).length}`);
console.log(`lockup trim: ${region.width}x${region.height}\n`);
for (let r = 0; r < rows; r++) {
  let line = "";
  for (let c = 0; c < GRID_COLS; c++)
    line += cells[r * GRID_COLS + c] ? "#" : "·";
  console.log(line);
}
