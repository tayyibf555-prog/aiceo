/** Width in logical px of a rendered string (5px glyphs + 1px tracking). */
export function textWidth(str) {
  return str.length * 6 - 1;
}

/** Returns [{x,y}] pixel offsets for a string at origin 0,0. */
export function textPixels(str) {
  const out = [];
  let cx = 0;
  for (const ch of str.toUpperCase()) {
    const glyph = FONT[ch] || FONT[" "];
    for (let row = 0; row < 7; row++) {
      for (let bit = 0; bit < 5; bit++) {
        if (glyph[row] & (1 << (4 - bit))) out.push({ x: cx + bit, y: row });
      }
    }
    cx += 6;
  }
  return out;
}
